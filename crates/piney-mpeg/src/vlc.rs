//! The variable-length codes of ISO/IEC 13818-2 Annex B, written as the
//! standard prints them (bit strings, without the sign bit that follows a
//! motion code or a DCT coefficient), and a lookup-table decoder.

use std::sync::OnceLock;

use crate::bits::Bits;

/// A prefix-code decoder: a table indexed by the next `bits` bits, each
/// entry `value << 8 | length` (length 0: no code starts with those bits).
pub(crate) struct Vlc {
    bits: u32,
    table: Vec<i32>,
}

impl Vlc {
    fn new<'a>(codes: impl IntoIterator<Item = (&'a str, i32)>) -> Vlc {
        let codes: Vec<(&str, i32)> = codes.into_iter().collect();
        let bits = codes.iter().map(|(c, _)| c.len() as u32).max().unwrap_or(1);
        let mut table = vec![0i32; 1 << bits];
        for (code, value) in codes {
            let len = code.len() as u32;
            let prefix = u32::from_str_radix(code, 2).expect("a bit string");
            let first = (prefix << (bits - len)) as usize;
            for e in &mut table[first..first + (1 << (bits - len))] {
                assert_eq!(*e, 0, "code {code} overlaps another");
                *e = value << 8 | len as i32;
            }
        }
        Vlc { bits, table }
    }

    /// The next code's value, or None if no code matches.
    #[inline]
    pub fn decode(&self, b: &mut Bits) -> Option<i32> {
        let e = self.table[b.peek(self.bits) as usize];
        if e == 0 {
            return None;
        }
        b.skip((e & 0xff) as u32);
        Some(e >> 8)
    }
}

/// macroblock_type flags (Tables B.2 to B.4).
pub(crate) const MB_INTRA: i32 = 0x01;
pub(crate) const MB_PATTERN: i32 = 0x02;
pub(crate) const MB_BACKWARD: i32 = 0x04;
pub(crate) const MB_FORWARD: i32 = 0x08;
pub(crate) const MB_QUANT: i32 = 0x10;

/// macroblock_address_increment's escape (adds 33) and MPEG-1 stuffing.
pub(crate) const ADDR_ESCAPE: i32 = 0x100;
pub(crate) const ADDR_STUFFING: i32 = 0x101;

/// DCT coefficient values: `run << 8 | level`, or these.
pub(crate) const DCT_EOB: i32 = -1;
pub(crate) const DCT_ESCAPE: i32 = -2;

pub(crate) struct Tables {
    pub addr_inc: Vlc,
    /// macroblock_type by picture_coding_type - 1 (I, P, B).
    pub mb_type: [Vlc; 3],
    pub cbp: Vlc,
    /// motion_code with its sign bit: -16..=16.
    pub motion: Vlc,
    pub dc_luma: Vlc,
    pub dc_chroma: Vlc,
    /// Table B.14 (every non-intra block; intra blocks with
    /// intra_vlc_format 0), after the first coefficient.
    pub dct_zero: Vlc,
    /// Table B.15 (intra blocks with intra_vlc_format 1).
    pub dct_one: Vlc,
}

pub(crate) fn tables() -> &'static Tables {
    static T: OnceLock<Tables> = OnceLock::new();
    T.get_or_init(|| {
        let addr = ADDR_INC.iter().enumerate().map(|(i, &c)| (c, i as i32 + 1));
        let addr = addr.chain([("00000001000", ADDR_ESCAPE), ("00000001111", ADDR_STUFFING)]);
        let motion = MOTION.iter().enumerate().flat_map(|(m, &c)| {
            let m = m as i32;
            if m == 0 { vec![(c.to_string(), 0)] } else { vec![(format!("{c}0"), m), (format!("{c}1"), -m)] }
        });
        let motion: Vec<(String, i32)> = motion.collect();
        let dct = |t: &[(&'static str, u8, u8)], eob: &'static str| {
            let mut v: Vec<(&str, i32)> = t.iter().map(|&(c, r, l)| (c, i32::from(r) << 8 | i32::from(l))).collect();
            v.push(("000001", DCT_ESCAPE));
            v.push((eob, DCT_EOB));
            Vlc::new(v)
        };
        Tables {
            addr_inc: Vlc::new(addr),
            mb_type: [Vlc::new(MB_TYPE_I), Vlc::new(MB_TYPE_P), Vlc::new(MB_TYPE_B)],
            cbp: Vlc::new(CBP.iter().map(|&(c, v)| (c, i32::from(v)))),
            motion: Vlc::new(motion.iter().map(|(c, v)| (c.as_str(), *v))),
            dc_luma: Vlc::new(DC_LUMA.iter().enumerate().map(|(i, &c)| (c, i as i32))),
            dc_chroma: Vlc::new(DC_CHROMA.iter().enumerate().map(|(i, &c)| (c, i as i32))),
            dct_zero: dct(&TABLE_ZERO, "10"),
            dct_one: dct(&TABLE_ONE, "0110"),
        }
    })
}

